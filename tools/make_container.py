"""Write src/container.h: the empty IoStore container (.utoc/.ucas) that sits next to the registry pak.

The game mounts a .pak only when a .utoc/.ucas pair with the same name is next to it, so the registry pak gets an
empty one: a version 8 TOC with one chunk, the container header (no packages). The bytes come from the IoStore writer
of the Kiryu costume (its containers are mounted by the game), and are embedded in version.dll.

    python make_container.py <Kiryu/tools folder> [stem]
"""
import os
import sys
import tempfile

tools = sys.argv[1]
stem = sys.argv[2] if len(sys.argv) > 2 else "GZPro-Registry_99_P"
sys.path.insert(0, tools)
import iostore  # noqa: E402

with tempfile.TemporaryDirectory() as td:
    toc = iostore.TocWriter(stem)
    toc.write(os.path.join(td, "c.utoc"), os.path.join(td, "c.ucas"), iostore.ContainerHeader())
    utoc = open(os.path.join(td, "c.utoc"), "rb").read()
    ucas = open(os.path.join(td, "c.ucas"), "rb").read()


def arr(name, b):
    rows = [", ".join(f"0x{x:02x}" for x in b[i:i + 16]) for i in range(0, len(b), 16)]
    return f"static const uint8_t {name}[{len(b)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "container.h")
with open(out, "w") as f:
    f.write(f"// Generated by tools/make_container.py: the empty container {stem}.utoc/.ucas "
            f"(container id {toc.cid:016x}).\n#pragma once\n")
    f.write(arr("EMPTY_UTOC", utoc))
    f.write(arr("EMPTY_UCAS", ucas))
print("wrote", os.path.abspath(out), len(utoc), len(ucas))
